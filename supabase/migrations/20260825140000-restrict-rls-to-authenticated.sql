-- This Supabase project is shared with a separate, live "Guess History"
-- game that reads `images`/`prompts` anonymously to serve players. SELECT
-- policies are therefore left completely untouched here (including the
-- ready=true anon-read policies on images) to avoid degrading that game.
--
-- This migration only tightens INSERT/UPDATE/DELETE, which had no
-- legitimate anonymous use case and were the actual data-tampering risk
-- (anyone holding the public anon key could modify or delete any row).
-- Ownership-based policies (auth.uid() = user_id) are dropped rather than
-- kept, because the app has no per-user ownership model in practice --
-- images are generated by whichever signed-in user runs a job, regardless
-- of which user owns the source prompt.
--
-- No tables, rows, or SELECT policies are dropped by this migration.

-- prompts: tighten INSERT/UPDATE/DELETE only
DROP POLICY IF EXISTS "Allow public delete access to prompts" ON public.prompts;
DROP POLICY IF EXISTS "Allow public insert access to prompts" ON public.prompts;
DROP POLICY IF EXISTS "Allow prompt inserts for signed-in users" ON public.prompts;
DROP POLICY IF EXISTS "Allow public update access to prompts" ON public.prompts;
DROP POLICY IF EXISTS "Authenticated users can update prompts" ON public.prompts;
DROP POLICY IF EXISTS "prompts_update_ready" ON public.prompts;

CREATE POLICY "Authenticated users can insert prompts" ON public.prompts
  FOR INSERT WITH CHECK (auth.uid() IS NOT NULL);

CREATE POLICY "Authenticated users can update prompts" ON public.prompts
  FOR UPDATE USING (auth.uid() IS NOT NULL);

CREATE POLICY "Authenticated users can delete prompts" ON public.prompts
  FOR DELETE USING (auth.uid() IS NOT NULL);

-- images: tighten INSERT/UPDATE/DELETE only; all SELECT policies
-- (including the anon ready=true policy the game likely relies on) are
-- left untouched.
DROP POLICY IF EXISTS "Allow public delete access to images" ON public.images;
DROP POLICY IF EXISTS "Public insert access for images" ON public.images;
DROP POLICY IF EXISTS "Allow public insert access to images" ON public.images;
DROP POLICY IF EXISTS "Public update access for images" ON public.images;
DROP POLICY IF EXISTS "Allow public update access to images" ON public.images;

CREATE POLICY "Authenticated users can insert images" ON public.images
  FOR INSERT WITH CHECK (auth.uid() IS NOT NULL);

CREATE POLICY "Authenticated users can update images" ON public.images
  FOR UPDATE USING (auth.uid() IS NOT NULL);

CREATE POLICY "Authenticated users can delete images" ON public.images
  FOR DELETE USING (auth.uid() IS NOT NULL);

-- project_tasks: left entirely untouched. It already has no INSERT/UPDATE/
-- DELETE policy (so those remain denied by default under RLS), and its
-- public SELECT policy is left alone since it is out of scope for this fix.
